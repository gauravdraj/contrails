// Wrap the unmodified browser scripts at build time: Workers cannot evaluate code.
// Each factory call owns fresh history, route and runway state.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ROOT = new URL("..", import.meta.url);
export const RUNTIME_FILE = "worker/src/board-runtime.generated.js";
export const SOURCES = ["js/data.js", "js/render.js", "js/airport-board.js"];

export async function buildBoardRuntime() {
  const appCore = await readFile(new URL("js/app-core.js", ROOT), "utf8");
  const bindings = appCore.split("\n").filter(line => /^const [A-Za-z_$][\w$]* = core\.[A-Za-z_$][\w$]*;$/.test(line));
  const parts = [
    "// Generated by worker/build-board-runtime.mjs from js/app-core.js, " + SOURCES.join(", ") + ". Do not edit.\n",
    "export function createBoardRuntime(G) {\nconst core = G.core;\n",
    bindings.join("\n") + "\n",
    "const FETCH_TIMEOUT_MS = 25000;\nconst SCHEDULE_CACHE_TTL = 5 * 60 * 1000;\n",
    "const posHistory = {};\nconst routeCache = {};\nconst scheduleDataCache = {};\nconst extraState = {};\n",
    "let airportData = G.airportData;\nlet runwayData = G.runwayData;\nlet aircraft = [];\nvar feedClockOffsetMs = null;\n",
    "const window = { localStorage: { getItem() { return null; }, setItem() {} } };\n",
    "const document = { addEventListener() {}, hidden: false };\n",
    "function isPrivate(callsign, type, category) { return core.isPrivateAircraft(callsign, type, category); }\n",
  ];
  for (const src of SOURCES) {
    const code = await readFile(new URL(src, ROOT), "utf8");
    parts.push("\n;// ---- " + src + " ----\n" + code);
  }
  parts.push("\nreturn { buildAircraftSnapshot, applyAirportScheduleMatches, buildLiveScheduleData, validateCachedRoute, scheduleDataCache, routeCache, mergeActiveRunways };\n}\n");
  return parts.join("");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = await buildBoardRuntime();
  const target = new URL(RUNTIME_FILE, ROOT);
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== output) {
      console.error(RUNTIME_FILE + " is out of date: run node worker/build-board-runtime.mjs");
      process.exit(1);
    }
    console.log(RUNTIME_FILE + " is up to date.");
  } else {
    await writeFile(target, output);
    console.log("Wrote " + RUNTIME_FILE + " (" + output.length + " bytes).");
  }
}
